
import  {getUserNotes, updateNote, deleteNotes,  deleteNoteById , addNote} from '../controllers/notes.controllers.js';
import {fetchuser} from '../middleware/fetchuser.js';
import express from 'express';
//ROUTE 1: hader 'auth-token' value 'token'
//get all the notes using: GET '/api/notes/getuser'. Login required

const router = express.Router();

router.route('/getUserNotes').get(fetchuser, getUserNotes)

router.route('/addNote').post(fetchuser, addNote)

//backend router defines the name of the variable inside the URL using a colon (:). 
//The controller must use that exact same variable name when reading req.params.
router.route('/updateNote/:noteId').put(fetchuser,updateNote)


router.route('/deleteNotes').delete(fetchuser,deleteNotes)

router.route('/deleteNoteById/:noteId').delete(fetchuser,deleteNoteById)




//notes.js (The Data Manager): This file is all about Operations. It handles your database actions: reading, adding, updating, and deleting notes (CRUD). It refuses to do anything unless a user provides the token generated by auth.js.

export default router;